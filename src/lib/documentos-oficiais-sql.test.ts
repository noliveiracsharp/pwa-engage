import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
import { expect, it } from 'vitest';
it('migra categorias, impede duplicidade e categoria de outra empresa, preserva arquivos e propaga edição',async()=>{
 const db=new PGlite();
 const empresa='00000000-0000-0000-0000-000000000001';
 const outra='00000000-0000-0000-0000-000000000002';
 await db.exec(`CREATE ROLE authenticated; CREATE ROLE service_role;
 CREATE FUNCTION app_usuario_empresa_id() RETURNS uuid LANGUAGE sql AS $$SELECT '${empresa}'::uuid$$;
 CREATE FUNCTION app_is_master() RETURNS boolean LANGUAGE sql AS $$SELECT false$$;
 CREATE FUNCTION documentos_oficiais_permissao(text) RETURNS boolean LANGUAGE sql AS $$SELECT true$$;
 CREATE TABLE empresas(id uuid PRIMARY KEY); INSERT INTO empresas VALUES('${empresa}'),('${outra}');
 CREATE TABLE documentos_oficiais(id uuid DEFAULT gen_random_uuid() PRIMARY KEY,empresa_id uuid,titulo text,categoria text,arquivo_url text,nome_arquivo text);
 INSERT INTO documentos_oficiais(empresa_id,titulo,categoria,arquivo_url,nome_arquivo) VALUES('${empresa}','Manual','Escritório','privado://original','manual.pdf'),('${empresa}','Guia','Escritorio','privado://guia','guia.pdf');`);
 const sql=readFileSync('supabase/sql/conectcon-documentos-oficiais-completo.sql','utf8');
 await db.exec(sql); await db.exec(sql);
 expect((await db.query('SELECT * FROM documentos_oficiais_categorias')).rows).toHaveLength(1);
 await expect(db.exec(`INSERT INTO documentos_oficiais_categorias(empresa_id,nome) VALUES('${empresa}','ESCRITÓRIO')`)).rejects.toThrow();
 await db.exec(`UPDATE documentos_oficiais_categorias SET nome='Institucional'; UPDATE documentos_oficiais SET titulo='Manual atualizado',descricao='Resumo',emissor='Fornecedor';`);
 const rows=(await db.query<{categoria:string;arquivo_url:string}>('SELECT categoria,arquivo_url FROM documentos_oficiais ORDER BY nome_arquivo')).rows;
 expect(rows.map(r=>r.categoria)).toEqual(['Institucional','Institucional']);
 expect(rows.map(r=>r.arquivo_url)).toEqual(['privado://guia','privado://original']);
 await expect(db.exec('DELETE FROM documentos_oficiais_categorias')).rejects.toThrow();
 await db.exec(`INSERT INTO documentos_oficiais_categorias(empresa_id,nome) VALUES('${outra}','Privada');`);
 await expect(db.exec(`UPDATE documentos_oficiais SET categoria_id=(SELECT id FROM documentos_oficiais_categorias WHERE empresa_id='${outra}')`)).rejects.toThrow();
 await db.exec('SET ROLE authenticated');
 const visiveis=(await db.query<{nome:string}>('SELECT nome FROM documentos_oficiais_categorias')).rows;
 expect(visiveis.map(r=>r.nome)).toEqual(['Institucional']);
 await db.close();
},30000);